CREATE TABLE IF NOT EXISTS silver.yellow_taxi_trips (
    "VendorID" INTEGER,
    tpep_pickup_datetime TIMESTAMP WITHOUT TIME ZONE,
    tpep_dropoff_datetime TIMESTAMP WITHOUT TIME ZONE,
    passenger_count INTEGER,
    trip_distance NUMERIC(18,6),
    "RatecodeID" INTEGER,
    store_and_fwd_flag TEXT,
    "PULocationID" INTEGER,
    "DOLocationID" INTEGER,
    payment_type INTEGER,
    fare_amount NUMERIC(18,2),
    extra NUMERIC(18,2),
    mta_tax NUMERIC(18,2),
    tip_amount NUMERIC(18,2),
    tolls_amount NUMERIC(18,2),
    improvement_surcharge NUMERIC(18,2),
    total_amount NUMERIC(18,2),
    congestion_surcharge NUMERIC(18,2),
    "Airport_fee" NUMERIC(18,2),
    cbd_congestion_fee NUMERIC(18,2),
    rejection_reasons TEXT NOT NULL,
    quality_flags TEXT NOT NULL,
    reference_month VARCHAR(7) NOT NULL,
    source_file TEXT NOT NULL,
    is_valid_revenue_payment BOOLEAN NOT NULL,
    quality_status VARCHAR(20) NOT NULL,
    pickup_date DATE,
    pickup_year_month VARCHAR(6),
    trip_duration_minutes NUMERIC(12,2),
    is_valid_trip BOOLEAN NOT NULL,
    invalid_reason TEXT NOT NULL
);
